// Generates src/app/core/models/contract.ts from docs/contract/*.schema.json.
// Run through `just contract`; never edit the output by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const contractDir = new URL('../../../docs/contract/', import.meta.url);
const output = new URL('../src/app/core/models/contract.ts', import.meta.url);
const roots = {
  GraphSnapshot: 'snapshot.schema.json',
  GraphDiff: 'diff.schema.json',
  SnapshotResponse: 'snapshot-response.schema.json',
  DiffResponse: 'diff-response.schema.json',
  MetaResponse: 'meta-response.schema.json',
  ApiError: 'api-error.schema.json',
  ReviewSummary: 'review-summary.schema.json',
  ImpactResponse: 'impact-response.schema.json',
  MetricsResponse: 'metrics-response.schema.json',
  CoChangeResponse: 'co-change-response.schema.json',
  ReviewState: 'review-state.schema.json',
  Settings: 'settings.schema.json',
  RepoComparison: 'repo-comparison.schema.json',
  ReadingOrderResponse: 'reading-order-response.schema.json',
  CommitReadingResponse: 'commit-reading-response.schema.json',
  LogResponse: 'log-response.schema.json',
  SearchResponse: 'search-response.schema.json',
  EdgeUsagesResponse: 'edge-usages-response.schema.json',
  RulesResponse: 'rules-response.schema.json',
};

const withoutTitle = ({ title, ...rest }) => rest;

const defs = {};
for (const [name, file] of Object.entries(roots)) {
  const {
    $schema,
    $defs = {},
    ...root
  } = JSON.parse(readFileSync(new URL(file, contractDir), 'utf8'));
  for (const [defName, def] of Object.entries($defs)) {
    if (
      defName in defs &&
      JSON.stringify(withoutTitle(defs[defName])) !== JSON.stringify(withoutTitle(def))
    ) {
      throw new Error(`${file}: definition ${defName} differs between schemas`);
    }
    defs[defName] = def;
  }
  if (!(name in defs)) defs[name] = root;
}

const bundle = {
  title: 'Contract',
  type: 'object',
  properties: Object.fromEntries(
    Object.keys(roots).map((name) => [name, { $ref: `#/$defs/${name}` }]),
  ),
  required: Object.keys(roots),
  $defs: defs,
};

const banner = '/* Generated by `just contract` from docs/contract/*.schema.json. Do not edit. */';
const source = await compile(bundle, 'Contract', {
  bannerComment: banner,
  additionalProperties: false,
  format: false,
});
writeFileSync(output, source);
